import sharp from "sharp";
import fs from "fs";

// Generates the launch splash assets:
// - lib/launch-splash-logo.ts: the white logo (from public/brand-logo.png) inlined as a data URI, so the
//   splash paints with no image request.
// - public/splash/ios-*.png: iOS startup images (iOS ignores the manifest's background_color). Plain
//   splash blue, so launch shows nothing but blue until the animated splash fades in.
const BACKGROUND = "#0f4c81";
const LOGO_MAX_WIDTH = 152; // min(9.5rem, 42vw) in lib/launch-splash.ts

const alpha = await sharp("public/brand-logo.png").extractChannel("alpha").png().toBuffer();
const inlineAlpha = await sharp(alpha).resize(LOGO_MAX_WIDTH * 2).png().toBuffer();
const { width: inlineW, height: inlineH } = await sharp(inlineAlpha).metadata();
const inlineLogo = await sharp({
  create: { width: inlineW, height: inlineH, channels: 3, background: "#ffffff" },
})
  .joinChannel(inlineAlpha)
  .png({ palette: true, colours: 16, compressionLevel: 9 })
  .toBuffer();
fs.writeFileSync(
  "lib/launch-splash-logo.ts",
  `// Generated by scripts/generate-launch-splash.mjs\nexport const launchSplashLogo = "data:image/png;base64,${inlineLogo.toString("base64")}";\n`,
);
console.log("lib/launch-splash-logo.ts");

const screens = JSON.parse(fs.readFileSync("lib/ios-splash-screens.json", "utf8"));
fs.mkdirSync("public/splash", { recursive: true });

for (const { width, height, ratio } of screens) {
  const file = `public/splash/ios-${width}x${height}@${ratio}x.png`;
  await sharp({
    create: { width: width * ratio, height: height * ratio, channels: 3, background: BACKGROUND },
  })
    .png({ compressionLevel: 9 })
    .toFile(file);
  console.log(file);
}

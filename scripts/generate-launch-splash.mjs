import sharp from "sharp";
import fs from "fs";

// Generates the launch assets from public/brand-logo.png so the OS launch screen and the animated
// splash (lib/launch-splash.ts) show the same fish at the same size, centred on screen:
// - lib/launch-splash-logo.ts: the white logo inlined as a data URI, so the splash paints with no image request.
// - public/icon-maskable-512.png: Android draws this on its launch screen at 240dp (inside a 160dp circle);
//   the fish is scaled so it renders LOGO_WIDTH wide there and clears the circle.
// - public/splash/ios-*.png: iOS startup images (iOS ignores the manifest's background_color).
const BACKGROUND = "#0f4c81";
const LOGO_WIDTH = 128; // keep in sync with .launch-splash-logo-wrap in lib/launch-splash.ts
const ANDROID_SPLASH_ICON_DP = 240;

const alpha = await sharp("public/brand-logo.png").extractChannel("alpha").png().toBuffer();

async function whiteLogo(width, paletteColours) {
  const resized = await sharp(alpha).resize(width).png().toBuffer();
  const { width: w, height: h } = await sharp(resized).metadata();
  const png = await sharp({ create: { width: w, height: h, channels: 3, background: "#ffffff" } })
    .joinChannel(resized)
    .png(paletteColours ? { palette: true, colours: paletteColours, compressionLevel: 9 } : {})
    .toBuffer();
  return { png, width: w, height: h };
}

async function centredOnBlue(width, height, logoWidth) {
  const logo = await whiteLogo(logoWidth);
  return sharp({ create: { width, height, channels: 3, background: BACKGROUND } }).composite([
    {
      input: logo.png,
      left: Math.round((width - logo.width) / 2),
      top: Math.round((height - logo.height) / 2),
    },
  ]);
}

const inline = await whiteLogo(LOGO_WIDTH * 2, 16);
fs.writeFileSync(
  "lib/launch-splash-logo.ts",
  `// Generated by scripts/generate-launch-splash.mjs\nexport const launchSplashLogo = "data:image/png;base64,${inline.png.toString("base64")}";\n`,
);
console.log("lib/launch-splash-logo.ts");

const maskable = await centredOnBlue(512, 512, Math.round((512 * LOGO_WIDTH) / ANDROID_SPLASH_ICON_DP));
await maskable.png({ compressionLevel: 9 }).toFile("public/icon-maskable-512.png");
console.log("public/icon-maskable-512.png");

const screens = JSON.parse(fs.readFileSync("lib/ios-splash-screens.json", "utf8"));
fs.mkdirSync("public/splash", { recursive: true });

for (const { width, height, ratio } of screens) {
  const file = `public/splash/ios-${width}x${height}@${ratio}x.png`;
  const image = await centredOnBlue(width * ratio, height * ratio, LOGO_WIDTH * ratio);
  await image.png({ compressionLevel: 9 }).toFile(file);
  console.log(file);
}
